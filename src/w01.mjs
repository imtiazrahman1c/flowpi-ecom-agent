export class SafeError extends Error { constructor(code,status=400){ super(code); this.code=code; this.status=status; } }
const uuid=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
export function validateEvent(v){
 if(!v || !uuid.test(v.merchant_id??'')) throw new SafeError('invalid_merchant');
 for(const k of ['event_id','customer_id']) if(typeof v[k]!=='string'||!v[k].trim()||v[k].length>160) throw new SafeError('invalid_'+k);
 if(!['website','messenger','whatsapp','instagram'].includes(v.channel)) throw new SafeError('invalid_channel');
 if(typeof v.text!=='string'||!v.text.trim()||v.text.length>4000) throw new SafeError('invalid_text');
 if(v.media_type && v.media_type!=='text') throw new SafeError('media_requires_human',422);
 return {merchant_id:v.merchant_id,event_id:v.event_id,customer_id:v.customer_id,channel:v.channel,text:v.text.trim()};
}
export function language(text){return /[\u0980-\u09ff]/u.test(text)?'bn':/\b(ami|amar|apnar|apni|dam|koto|ache|ase|lagbe|chai|bhai|den|pabo|korbo|hobe)\b/i.test(text)?'banglish':'en';}
const words={bn:{handoff:'আপনার অনুরোধটি সাপোর্ট টিমের কাছে পাঠানো হয়েছে।',unknown:'পণ্যের নাম বা SKU এবং ভ্যারিয়েন্টটি জানাবেন?',stale:'বর্তমান দাম ও স্টক নিশ্চিত করা যাচ্ছে না। সাপোর্ট টিম যাচাই করবে।',none:'এই পণ্যটি পাওয়া যায়নি। নাম বা SKU আবার জানাবেন?',oos:'স্টকে নেই',stock:'স্টক',price:'দাম'},banglish:{handoff:'Apnar request support team-er kache pathano hoyeche.',unknown:'Product-er naam ba SKU ebong variant janaben?',stale:'Ekhon dam o stock confirm kora jacche na. Support team verify korbe.',none:'Product paoa jayni. Naam ba SKU abar janaben?',oos:'Stock-e nei',stock:'Stock',price:'Dam'},en:{handoff:'Your request has been passed to the support team.',unknown:'Please share the product name or SKU and variant.',stale:'Current price and stock could not be verified. Support will check.',none:'No matching product found. Please confirm its name or SKU.',oos:'Out of stock',stock:'Stock',price:'Price'}};
export async function processEvent(input,{store,planner,now=()=>Date.now()}){
 const e=validateEvent(input), lang=language(e.text), w=words[lang];
 const claim=await store.begin(e);
 if(claim.status==='duplicate')return {status:'duplicate',send:false};
 if(claim.status==='busy')throw new SafeError('conversation_busy',409);
 if(claim.status==='human')return {status:'human_owned',send:false};
 try {
 let plan=await planner(e.text,claim.history??[],lang);
 if(!plan || !['product','faq','order','tracking','human','clarify'].includes(plan.intent))throw Error('invalid_plan');
 let reply=w.unknown,status='clarification',facts=[];
 if(['human','order','tracking'].includes(plan.intent)){
   // W02/W03 are not implemented; never claim an order or tracking action occurred.
   await store.handoff(e,plan.intent); reply=w.handoff;status='handoff';
 }else if(plan.intent==='product'){
   if(typeof plan.query!=='string'||!plan.query.trim()||plan.query.length>160)throw Error('invalid_query');
   const found=await store.search(e.merchant_id,plan.query.trim());
   const verified=await Promise.all(found.slice(0,5).map(p=>store.verify(e.merchant_id,p.id)));
   facts=verified.filter(Boolean);
   if(!facts.length)reply=w.none;
   else if(facts.some(p=>!Number.isSafeInteger(p.price_minor)||p.price_minor<0||!Number.isInteger(p.stock)||p.stock<0||p.currency!=='BDT'||!Number.isFinite(Date.parse(p.verified_at))||now()-Date.parse(p.verified_at)>60000||Date.parse(p.verified_at)>now()+5000)){
     await store.handoff(e,'catalog_unverified');reply=w.stale;status='handoff';facts=[];
   }else{
     // Prices and stock are rendered by code, never generated by the model.
     reply=facts.map(p=>`${p.name} [${p.sku}] — ${w.price}: BDT ${(p.price_minor/100).toFixed(2)}; ${p.stock>0?`${w.stock}: ${p.stock}`:w.oos}`).join('\n');status='answered';
   }
 }else if(plan.intent==='faq'){
   const policies=await store.policies(e.merchant_id,String(plan.query??'').slice(0,160));
   if(policies.length){reply=policies.map(p=>p.content).join('\n'); status='answered';}
   else{await store.handoff(e,'policy_not_verified');reply=w.handoff;status='handoff';}
 }
 // finish rechecks the human lock in the same DB transaction as writing the draft.
 const result=await store.finish(e,{reply,language:lang,status,facts});
 return {status:result.status,send:false,draft:result.status==='suppressed'?null:reply,language:lang};
 }catch(err){await store.fail(e);throw new SafeError('processing_failed',503);}
}
